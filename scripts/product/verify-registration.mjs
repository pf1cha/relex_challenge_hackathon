import {chromium} from '../../frontend/node_modules/playwright/index.mjs';
import {randomUUID} from 'node:crypto';
import {writeFileSync} from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();
const email='registration-'+randomUUID()+'@example.test', password=randomUUID()+'Aa1!';
const url='http://127.0.0.1:18080';
const checks=[];
try{
 await page.goto(url);
 await page.getByRole('button',{name:'Register',exact:true}).click();
 await page.getByLabel('Display name',{exact:true}).fill('Registration check');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 const created=page.waitForResponse(r=>r.url().endsWith('/api/register')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 if((await created).status()!==201)throw Error('Registration failed');
 await page.getByText('No project access has been assigned',{exact:false}).waitFor();
 checks.push('Browser registration201; new account has no existing project access');
 await page.reload();
 await page.getByText('No project access has been assigned',{exact:false}).waitFor();
 checks.push('Session persisted across browser reload');
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('button',{name:'Register',exact:true}).click();
 await page.getByLabel('Display name',{exact:true}).fill('Duplicate');
 await page.getByLabel('Email',{exact:true}).fill(email.toUpperCase());
 await page.getByLabel('Password',{exact:true}).fill(password);
 const duplicate=page.waitForResponse(r=>r.url().endsWith('/api/register')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 if((await duplicate).status()!==409)throw Error('Duplicate not rejected');
 await page.getByText('This email is already registered. Sign in instead.',{exact:true}).waitFor();
 checks.push('Case-insensitive duplicate409; visible recovery message');
 await page.getByRole('button',{name:'Back to sign in',exact:true}).click();
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByText('No project access has been assigned',{exact:false}).waitFor();
 checks.push('Original account password/login still works');
 const bad=await page.request.post(url+'/api/register',{headers:{Origin:url},data:{email:'invalid',password:'short',display_name:'Invalid'}});
 if(bad.status()!==422)throw Error('Invalid accepted');
 const cross=await page.request.post(url+'/api/register',{headers:{Origin:'https://other.invalid'},data:{email:'cross@example.test',password,display_name:'Cross'}});
 if(cross.status()!==403)throw Error('Cross origin accepted');
 checks.push('Invalid422 and untrusted origin403');
 const result={status:'PASS',checks,email};
 writeFileSync('.runtime/registration-browser.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
}finally{await browser.close()}
